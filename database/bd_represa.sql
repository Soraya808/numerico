CREATE DATABASE IF NOT EXISTS bd_represa CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE bd_represa;
CREATE TABLE IF NOT EXISTS simulaciones (
 id INT AUTO_INCREMENT PRIMARY KEY,
 fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 escenario VARCHAR(60) NOT NULL,
 V0 DOUBLE NOT NULL, A DOUBLE NOT NULL, C DOUBLE NOT NULL, k DOUBLE NOT NULL,
 Vm DOUBLE NOT NULL, T DOUBLE NOT NULL, h1 DOUBLE NOT NULL, h2 DOUBLE NOT NULL,
 aporte_neto DOUBLE NOT NULL, dia_critico DOUBLE NULL,
 exacta_final DOUBLE NOT NULL, heun_final DOUBLE NOT NULL, rk4_final DOUBLE NOT NULL,
 error_heun DOUBLE NOT NULL, error_rk4 DOUBLE NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS detalle_simulacion (
 id INT AUTO_INCREMENT PRIMARY KEY,
 simulacion_id INT NOT NULL,
 paso VARCHAR(10) NOT NULL,
 numero_paso INT NOT NULL,
 tiempo DOUBLE NOT NULL, exacta DOUBLE NOT NULL, heun DOUBLE NOT NULL, rk4 DOUBLE NOT NULL,
 CONSTRAINT fk_detalle_sim FOREIGN KEY (simulacion_id) REFERENCES simulaciones(id) ON DELETE CASCADE
) ENGINE=InnoDB;
